import {syncWorkbook} from './content-workbook.mjs';
import {refreshSubstack} from './substack.mjs';
import {cp,mkdir,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
await syncWorkbook();
await refreshSubstack();
const out=path.join(root,'dist');
await mkdir(out,{recursive:true});
for(const file of ['index.html','styles.css','theme.css','app.js','assets','content'])await cp(path.join(root,file),path.join(out,file),{recursive:true});
console.log('Built static website in '+out);
